<?php

namespace App\Console\Commands;

use Illuminate\Console\Attributes\Description;
use Illuminate\Console\Attributes\Signature;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\File;

/**
 * php artisan serve answers one request at a time on Windows: with several visitors at the booth, every answer
 * waits for the one before it (2-4 s each while the AI replies). Laragon's Apache with mod_php serves many at once.
 * This writes a config of our own (Laragon's settings are not touched) and prints the httpd.exe to start it with.
 */
#[Signature('voic:apache {--port=8000} {--threads=64} {--apache-dir= : Apache folder (default: newest in C:\laragon\bin\apache)}')]
#[Description('Write an Apache config for the booth web server and print the path of httpd.exe')]
class ApacheConfig extends Command
{
    public function handle(): int
    {
        $httpd = $this->findHttpd();
        $phpDir = dirname(PHP_BINARY);
        $module = $phpDir.DIRECTORY_SEPARATOR.'php8apache2_4.dll';

        if ($httpd === null) {
            $this->components->warn('Apache tidak ditemukan (C:\laragon\bin\apache).');

            return self::FAILURE;
        }
        // mod_php needs the thread-safe PHP build and its Apache module next to php.exe.
        if (! PHP_ZTS || ! is_file($module)) {
            $this->components->warn('PHP ini tidak punya modul Apache (php8apache2_4.dll, versi Thread Safe).');

            return self::FAILURE;
        }

        $config = $this->config(dirname($httpd, 2), $phpDir, $module);
        $path = storage_path('app/apache/httpd.conf');
        File::ensureDirectoryExists(dirname($path));
        File::put($path, $config);

        $this->line($this->slashes($httpd));

        return self::SUCCESS;
    }

    protected function findHttpd(): ?string
    {
        $dirs = $this->option('apache-dir')
            ? [(string) $this->option('apache-dir')]
            : (glob('C:/laragon/bin/apache/*', GLOB_ONLYDIR) ?: []);
        // Newest version first: httpd-2.4.68-... sorts after httpd-2.4.62-...
        usort($dirs, fn ($a, $b) => version_compare(basename($b), basename($a)) ?: strcmp($b, $a));

        foreach ($dirs as $dir) {
            if (is_file($dir.'/bin/httpd.exe')) {
                return $dir.'/bin/httpd.exe';
            }
        }

        return null;
    }

    protected function config(string $apacheDir, string $phpDir, string $module): string
    {
        $root = $this->slashes($apacheDir);
        $php = $this->slashes($phpDir);
        $public = $this->slashes(public_path());
        $port = (int) $this->option('port');
        $threads = max(8, (int) $this->option('threads'));
        $pid = $this->slashes(storage_path('app/apache/httpd.pid'));
        $log = $this->slashes(storage_path('logs/apache-error.log'));

        // Laragon loads these before mod_php: PHP's curl/openssl need them and Apache ships older copies.
        $libraries = '';
        foreach (['libcrypto-3-x64.dll', 'libssl-3-x64.dll', 'libssh2.dll', 'nghttp2.dll'] as $dll) {
            if (is_file($phpDir.DIRECTORY_SEPARATOR.$dll)) {
                $libraries .= "LoadFile \"{$php}/{$dll}\"\n";
            }
        }
        $moduleFile = $this->slashes($module);

        return <<<CONF
# Generated by `php artisan voic:apache` (jalankan_voic.bat). Do not edit: it is rewritten on every start.
ServerRoot "{$root}"
Listen 0.0.0.0:{$port}
ServerName localhost
PidFile "{$pid}"
ErrorLog "{$log}"
LogLevel warn

# Windows MPM: one process with many threads; each visitor's request gets its own.
ThreadsPerChild {$threads}
MaxConnectionsPerChild 0
AcceptFilter http none
AcceptFilter https none
EnableSendfile off
EnableMMAP off
# The local AI can take a minute or more to answer on a laptop CPU.
Timeout 300
KeepAlive On
KeepAliveTimeout 5

LoadModule authz_core_module modules/mod_authz_core.so
LoadModule dir_module modules/mod_dir.so
LoadModule mime_module modules/mod_mime.so
LoadModule rewrite_module modules/mod_rewrite.so
LoadModule headers_module modules/mod_headers.so
LoadModule filter_module modules/mod_filter.so
LoadModule deflate_module modules/mod_deflate.so
LoadModule setenvif_module modules/mod_setenvif.so
TypesConfig conf/mime.types

{$libraries}LoadModule php_module "{$moduleFile}"
PHPIniDir "{$php}"

DocumentRoot "{$public}"
<Directory />
    AllowOverride None
    Require all denied
</Directory>
<Directory "{$public}">
    Options FollowSymLinks
    AllowOverride All
    Require all granted
</Directory>
DirectoryIndex index.php
<FilesMatch "\.php$">
    SetHandler application/x-httpd-php
</FilesMatch>

# Smaller pages and scripts on visitors' phones. Not the examiner's streamed reply (application/x-ndjson),
# which must reach the browser sentence by sentence.
AddOutputFilterByType DEFLATE text/html text/css text/plain application/javascript text/javascript application/json image/svg+xml
# Built assets have a content hash in their name: the phone may keep them.
<Directory "{$public}/build">
    Header set Cache-Control "public, max-age=31536000, immutable"
</Directory>

CONF;
    }

    protected function slashes(string $path): string
    {
        return str_replace('\\', '/', $path);
    }
}
